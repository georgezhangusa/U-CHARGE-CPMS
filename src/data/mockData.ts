      const isCharging = num % 3 === 0;
      const isFaulted = num === 307;
      const port1Status: PortStatus = isFaulted ? 'Faulted' : isCharging ? 'Charging' : 'Available';
      const port2Status: PortStatus = isFaulted ? 'Faulted' : num % 4 === 0 ? 'Charging' : 'Available';
